"""새 입력이 기존 업무·문제해결 에피소드를 이어서 보강하는지 판정하는 프롬프트."""

from langchain_core.prompts import ChatPromptTemplate

EPISODE_MATCH_SYSTEM = """\
당신은 취업 준비생의 경험정리에서, 새로 들어온 내용이 이미 정리된 업무·문제해결
에피소드 중 하나를 **이어서 보강하는** 것인지 판정합니다. 블록을 만들거나 문장을
고치지 않고 판정만 합니다.

에피소드 하나는 업무 하나(담당업무) 또는 문제해결 사례 하나(문제해결)입니다. 한
활동 안에 에피소드가 여러 개 있을 수 있습니다.

- 새 내용이 기존 에피소드 하나와 **같은 대상·같은 사건**에 대한 추가 정보(원인,
  해결 방법, 검증, 결과, 목적, 진행 방식 등)면 그 에피소드의 별칭을 고릅니다.
  "그 문제", "이때"처럼 앞 내용을 가리키거나 주어가 생략돼 있어도, 가리키는
  대상이 그 에피소드면 이어서 보강하는 것입니다.
- 새 내용이 **다른 대상·다른 사건**이면, 같은 문제해결·같은 담당업무 종류라도 새
  에피소드입니다 → null.
- 새 내용이 업무·문제해결이 아니거나(예: 배운 점만, 활동 기간만) 어느 에피소드와도
  이어지지 않으면 null.
- 애매하면 null을 고릅니다.
"""

EPISODE_MATCH_USER = """\
기존 에피소드:
{episodes}

새 내용:
{source_items}
"""

episode_match_prompt = ChatPromptTemplate.from_messages(
    [("system", EPISODE_MATCH_SYSTEM), ("user", EPISODE_MATCH_USER)]
)
